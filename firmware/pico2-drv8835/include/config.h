#define PIN_CONFLICTS_DRV8835_OR_SERVO(pin) \
    ((pin) == PIN_PEN_SERVO_PWM || (pin) == PIN_DRV_X_A_IN1 || \
     (pin) == PIN_DRV_X_A_IN2 || (pin) == PIN_DRV_X_B_IN1 || \
     (pin) == PIN_DRV_X_B_IN2 || (pin) == PIN_DRV_Y_C_IN1 || \
     (pin) == PIN_DRV_Y_C_IN2 || (pin) == PIN_DRV_Y_D_IN1 || \
     (pin) == PIN_DRV_Y_D_IN2)

#if PIN_CONFLICTS_DRV8835_OR_SERVO(PIN_CURRENT_SENSOR_XA_GPIO)
#error "Current sensor ADC pin conflicts with a DRV8835 or servo output"
#endif
#if PIN_CONFLICTS_DRV8835_OR_SERVO(PIN_AS5600_J1_SDA) || \
    PIN_CONFLICTS_DRV8835_OR_SERVO(PIN_AS5600_J1_SCL) || \
    PIN_CONFLICTS_DRV8835_OR_SERVO(PIN_AS5600_J2_SDA) || \
    PIN_CONFLICTS_DRV8835_OR_SERVO(PIN_AS5600_J2_SCL)
#error "AS5600 I2C pins conflict with a DRV8835 or servo output"
#endif

